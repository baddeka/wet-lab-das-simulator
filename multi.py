import numpy as np

print("=== ВАРИАНТ A: несколько маркеров, но один канал (всё жжёт один фермент) ===")
print("   H2O2 от всех маркеров складывается, прибор видит одну цифру.")
print()
print("   %-38s %s" % ("смесь", "итоговое R"))
def combined_R(levels, ratios, eff=None):
    eff = eff or [1.0]*len(levels)
    h = sum(e*l for e, l in zip(eff, levels))
    s = sum(e*l*r for e, l, r in zip(eff, levels, ratios))
    return s/h
cases = [
    ("только DAS (0.2 uM, R=1.67)",              [0.2], [1.67]),
    ("DAS + ацетилспермидин 2 uM, R=1.3",        [0.2, 2.0], [1.67, 1.3]),
    ("DAS + ацетилспермидин 2 uM, R=1.67",       [0.2, 2.0], [1.67, 1.67]),
    ("DAS + ацетилспермидин 2 uM, R=2.5",        [0.2, 2.0], [1.67, 2.5]),
    ("DAS + 3 полиамина по 2 uM, все R=1.3",     [0.2, 2., 2., 2.], [1.67, 1.3, 1.3, 1.3]),
]
for lbl, lv, rt in cases:
    print("   %-38s %.3f" % (lbl, combined_R(lv, rt)))
print()
print("   ПРАВИЛО: итоговое R это среднее взвешенное по вкладу каждого маркера в фон.")
print("   Оно ВСЕГДА между минимальным и максимальным R. Превысить лучший маркер нельзя.")
print("   А так как обильных маркеров больше, они и перетягивают среднее на себя.")
print()

print("=== ВАРИАНТ B: несколько маркеров, каждый в своём канале, потом объединяем ===")
print("   z одного маркера при кратности 1.20, CV 10 %, n = 3:")
z1 = np.log(1.20)/(0.10*np.sqrt(2/3))
print("      z = %.2f   (нужно 2.8)" % z1)
print()
print("   объединение k маркеров, при корреляции rho между ними:")
print("   %-8s %-11s %-11s %-11s %-11s" % ("k", "rho=0", "rho=0.5", "rho=0.8", "rho=0.95"))
for k in [1, 2, 3, 4, 6]:
    row = []
    for rho in [0.0, 0.5, 0.8, 0.95]:
        zc = z1*np.sqrt(k/(1 + (k-1)*rho))
        row.append("%.2f %s" % (zc, "OK " if zc >= 2.8 else "нет"))
    print("   %-8d %-11s %-11s %-11s %-11s" % (k, *row))
print()
print("   полиамины одного пути сильно скоррелированы, rho порядка 0.8 и выше.")
print("   маркеры из разной биологии почти независимы, rho близко к 0.")
